//! Renders the human-readable helper catalogue from the cards.
//!
//! The page depends only on the card files, so `check` can tell whether it
//! is current without touching the source tree, and code that moves never
//! makes it outdated. Entry points link to their files, not to lines; the
//! lines at the checked commit are in `report.json`.

use std::fmt::Write;

use super::card::{Card, CardSource, Catalogue, Status, UNKNOWN};

pub(crate) const PAGE_FILE: &str = "helpers.md";

/// Section heading of a family prefix (`container.ring` -> `container`).
fn domain_title(prefix: &str) -> &str {
    match prefix {
        "container" => "Containers",
        "id" => "ID allocation",
        "sync" => "Locks, waiting and synchronisation",
        "task" => "Tasks, work and timers",
        "irq" => "Interrupt deferral",
        "cpu" => "CPU-local data and cross-CPU calls",
        "mm" => "Memory, user memory and DMA",
        "io" => "I/O buffers, traits and MMIO",
        "parse" => "Parsing",
        "error" => "Errors",
        "time" => "Time",
        "crypto" => "Cryptography",
        "misc" => "Miscellaneous",
        other => other,
    }
}

fn prefix(family: &str) -> &str {
    family.split('.').next().unwrap_or(family)
}

/// Markdown anchor GitHub/Gitee derive from a heading.
fn anchor(heading: &str) -> String {
    heading
        .to_lowercase()
        .chars()
        .filter_map(|c| match c {
            ' ' => Some('-'),
            c if c.is_alphanumeric() || c == '-' || c == '_' => Some(c),
            _ => None,
        })
        .collect()
}

/// Card prose on one line, with `<` escaped outside code spans so generic
/// parameters such as `ArrayVec<T, CAP>` are not read as HTML.
fn one_line(text: &str) -> String {
    let joined = text.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut out = String::with_capacity(joined.len());
    let mut in_code = false;
    for c in joined.chars() {
        match c {
            '`' => {
                in_code = !in_code;
                out.push(c);
            }
            '<' if !in_code => out.push_str("&lt;"),
            _ => out.push(c),
        }
    }
    out
}

pub(crate) fn render(catalogue: &Catalogue) -> String {
    let mut cards: Vec<&Card> = catalogue
        .cards
        .iter()
        .filter(|card| card.status != Status::Retired)
        .collect();
    let family_rank = |family: &str| {
        catalogue
            .meta
            .families
            .iter()
            .position(|known| known == family)
            .unwrap_or(usize::MAX)
    };
    let mut domains: Vec<&str> = Vec::new();
    for family in catalogue.meta.families.iter().map(String::as_str) {
        if !domains.contains(&prefix(family)) {
            domains.push(prefix(family));
        }
    }
    cards.sort_by(|a, b| {
        (family_rank(&a.family), &a.family, &a.capability).cmp(&(
            family_rank(&b.family),
            &b.family,
            &b.capability,
        ))
    });
    for card in &cards {
        if !domains.contains(&prefix(&card.family)) {
            domains.push(prefix(&card.family));
        }
    }

    let mut out = String::new();
    out.push_str(
        "<!-- Generated by `xkmake capability render` from cards/*.yaml; do not edit. -->\n\n# \
         Helper catalogue\n\nReusable capabilities of X-Kernel and its locked dependencies. \
         Before writing a\nhelper, container, lock, parser or allocator, look for it here; the \
         card\nlinked from each entry holds the evidence (file, item and quote) for every \
         claim.\nHow the catalogue is kept current: [README.md](README.md).\n\n",
    );
    if !catalogue.meta.notice.trim().is_empty() {
        let _ = writeln!(out, "> **Note:** {}\n", one_line(&catalogue.meta.notice));
    }
    out.push_str(
        "Contract values are quoted from the source; `unknown` means no evidence was\nfound, not \
         that the property is absent. Check the card before relying on a\ncontract in IRQ, NMI or \
         allocation-free code.\n\n## Contents\n\n",
    );
    for domain in &domains {
        let in_domain: Vec<&&Card> = cards
            .iter()
            .filter(|card| prefix(&card.family) == *domain)
            .collect();
        if in_domain.is_empty() {
            continue;
        }
        let title = domain_title(domain);
        let _ = writeln!(out, "- [{title}](#{})", anchor(title));
        for card in in_domain {
            let _ = writeln!(
                out,
                "  - [{}](#{}) — `{}`",
                one_line(&card.title),
                anchor(&card.capability),
                card.family
            );
        }
    }
    for domain in &domains {
        let in_domain: Vec<&&Card> = cards
            .iter()
            .filter(|card| prefix(&card.family) == *domain)
            .collect();
        if in_domain.is_empty() {
            continue;
        }
        let _ = writeln!(out, "\n## {}", domain_title(domain));
        for card in in_domain {
            render_card(&mut out, card);
        }
    }
    if !catalogue.meta.absent.is_empty() {
        out.push_str("\n## Families without a reusable implementation\n\n");
        for absent in &catalogue.meta.absent {
            let _ = writeln!(out, "- `{}`: {}", absent.family, one_line(&absent.note));
        }
    }
    out
}

fn render_card(out: &mut String, card: &Card) {
    let _ = writeln!(out, "\n### {}\n", card.capability);
    let source = match &card.source {
        CardSource::Workspace { crate_name, path } => format!("crate `{crate_name}` (`{path}`)"),
        CardSource::Dependency {
            crate_name,
            version,
        } => format!("crates.io `{crate_name}` {version}"),
    };
    let _ = writeln!(
        out,
        "**{}** — {source}; family `{}`; card [cards/{}.yaml](cards/{}.yaml)\n",
        one_line(&card.title),
        card.family,
        card.capability,
        card.capability
    );
    match card.status {
        Status::Suspended => {
            let _ = writeln!(
                out,
                "> **Suspended:** {} Do not suggest it until the card is fixed.\n",
                one_line(&card.reason)
            );
        }
        Status::NeedsOwner => {
            let _ = writeln!(
                out,
                "> **Needs an owner decision.** Do not suggest it until these are answered:"
            );
            for question in &card.open_questions {
                let _ = writeln!(
                    out,
                    "> - `{}`: {}",
                    question.field,
                    one_line(&question.question)
                );
            }
            out.push('\n');
        }
        Status::Active | Status::Retired => {}
    }
    let _ = writeln!(out, "{}\n", one_line(&card.summary));
    let entry_points: Vec<String> = card
        .symbols
        .iter()
        .filter(|symbol| matches!(symbol.role.as_str(), "primary" | "constructor"))
        .map(|symbol| match &card.source {
            // The page lives two directories below the repository root.
            CardSource::Workspace { .. } => format!("[`{}`](../../{})", symbol.fqn, symbol.path),
            CardSource::Dependency { .. } => format!("`{}`", symbol.fqn),
        })
        .collect();
    if !entry_points.is_empty() {
        let _ = writeln!(out, "- Entry points: {}", entry_points.join(", "));
    }
    if !card.operations.is_empty() {
        let operations: Vec<String> = card
            .operations
            .iter()
            .map(|op| format!("`{}` ({})", op.name, one_line(&op.effect)))
            .collect();
        let _ = writeln!(out, "- Operations: {}", operations.join("; "));
    }
    let _ = writeln!(out, "- Contract:");
    for field in &card.contract {
        let label = match field.name.as_str() {
            "no_std" => "no_std",
            "allocation" => "allocation",
            "blocking" => "blocking",
            "irq_nmi" => "IRQ / NMI",
            "ownership_lifetime" => "ownership",
            "errors_bounds" => "errors / bounds",
            "concurrency" => "concurrency",
            other => other,
        };
        let value = one_line(&field.value);
        if value == UNKNOWN {
            let _ = writeln!(out, "  - {label}: `unknown`");
        } else {
            let _ = writeln!(out, "  - {label}: {value}");
        }
    }
    if !card.usage_protocol.is_empty() {
        let _ = writeln!(out, "- Usage:");
        for (index, step) in card.usage_protocol.iter().enumerate() {
            let _ = writeln!(out, "  {}. {}", index + 1, one_line(step));
        }
    }
    if !card.exclusions.is_empty() {
        let _ = writeln!(out, "- Do not use it when:");
        for exclusion in &card.exclusions {
            let _ = writeln!(out, "  - {}", one_line(exclusion));
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{anchor, one_line};

    #[test]
    fn anchors_follow_heading_slugs() {
        assert_eq!(
            anchor("Locks, waiting and synchronisation"),
            "locks-waiting-and-synchronisation"
        );
        assert_eq!(anchor("spsc_ring_ringbuf"), "spsc_ring_ringbuf");
    }

    #[test]
    fn prose_escapes_html_outside_code_spans() {
        assert_eq!(
            one_line("ArrayVec<T, CAP>\n  keeps `Vec<T>`"),
            "ArrayVec&lt;T, CAP> keeps `Vec<T>`"
        );
    }
}
