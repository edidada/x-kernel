#!/usr/bin/env python3
"""Generate the RK3588 CRU reset-line table for x-kernel from the pinned
Linux reference trees.

Two vendored references join by reset NAME (BSP numbering != mainline
numbering; the register positions are hardware facts shared by both):

  1. DT-binding ids (what `resets = <&cru N>` carries on this board):
     data/references/bsp-opi5plus/include/dt-bindings/clock/rockchip,rk3588-cru.h
     (the BSP header keeps its SRST_* defines inside the CLOCK header)
  2. id -> (domain, reg, bit) register positions:
     data/references/linux/drivers/clk/rockchip/rst-rk3588.c

The four register domains are arithmetic offsets from `reg_base =
CRU + 0xA00` (see the macro comments in the reference): CRU +0,
PHPTOPCRU +0x8000 bytes, SECURECRU +0x4000, PMU1CRU +0x30000. All fall
inside the CRU node's single 0x5C000 DT window.

BSP ids whose name has no mainline LUT row are reported as gaps and
skipped (they cannot be serviced faithfully).

Run from the repo root:
  python3 scripts/port-rk3588-reset/generate.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / "docs/ai/skills/linux-driver-port/data/references"
BSP_HDR = REF / "bsp-opi5plus/include/dt-bindings/clock/rockchip,rk3588-cru.h"
MLUT = REF / "linux/drivers/clk/rockchip/rst-rk3588.c"
OUT = ROOT / "drivers/drv/clk/src/rk3588_cru/reset_data.rs"

# reg_base = CRU + 0xA00; domain byte offsets from reg_base (LUT macros).
DOMAINS = {
    "RK3588_CRU_RESET_OFFSET": 0x0,
    "RK3588_PHPTOPCRU_RESET_OFFSET": 0x8000,
    "RK3588_SECURECRU_RESET_OFFSET": 0x4000,
    "RK3588_PMU1CRU_RESET_OFFSET": 0x30000,
}
CRU_SOFTRST_CON0 = 0xA00  # RK3588_SOFTRST_CON(0), from BSP clk.h


def parse_bsp_ids(path: Path) -> dict[str, int]:
    """SRST name -> BSP dt-binding id (the value the board dts carries)."""
    ids = {}
    for line in path.read_text().splitlines():
        m = re.match(r"#define\s+(SRST_\S+)\s+(0x[0-9a-fA-F]+|\d+)\s*$", line)
        if m:
            ids[m.group(1)] = int(m.group(2), 0)
    return ids


def parse_mainline_lut(path: Path) -> dict[str, tuple[str, int, int]]:
    """SRST name -> (domain macro, reg, bit) from the mainline LUT."""
    rows = {}
    for line in path.read_text().splitlines():
        m = re.match(
            r"\s*(RK3588_\w+_RESET_OFFSET)\((\S+),\s*(\d+),\s*(\d+)\),", line
        )
        if m:
            rows[m.group(2)] = (m.group(1), int(m.group(3)), int(m.group(4)))
    return rows


def main() -> int:
    bsp = parse_bsp_ids(BSP_HDR)
    lut = parse_mainline_lut(MLUT)

    # Join: BSP id -> name -> mainline (domain, reg, bit) -> absolute byte
    # offset from the CRU window base + bit.
    rows = []
    missing_lut = []
    for name, dts_id in sorted(bsp.items(), key=lambda kv: kv[1]):
        row = lut.get(name)
        if row is None:
            missing_lut.append((dts_id, name))
            continue
        domain, reg, bit = row
        byte = CRU_SOFTRST_CON0 + DOMAINS[domain] + reg * 4
        rows.append((dts_id, name, byte, bit))

    # BSP header aliases: two names may share one id; keep the row only
    # when every join lands on the same (byte, bit) — otherwise the id is
    # ambiguous and fail-closed removes it.
    by_id: dict[int, list] = {}
    for row in rows:
        by_id.setdefault(row[0], []).append(row)
    positions = {
        dts_id: {(byte, bit) for _, _, byte, bit in group}
        for dts_id, group in by_id.items()
    }
    ambiguous = sorted(dts_id for dts_id, pos in positions.items() if len(pos) > 1)
    rows = [
        group[0]
        for dts_id, group in sorted(by_id.items())
        if dts_id not in ambiguous
    ]
    dups = {}

    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright 2025 KylinSoft Co., Ltd. <https://www.kylinos.cn/>",
        "// See LICENSES for license details.",
        "",
        "// @generated by scripts/port-rk3588-reset/generate.py — do not edit by hand.",
        "//",
        "// BSP dt-binding id -> (register byte offset from the CRU window base, bit).",
        "// Joined by reset NAME across the pinned references:",
        "//   ids:   bsp-opi5plus dt-bindings (the numbering the board dts carries)",
        "//   positions: linux rst-rk3588.c LUT (four register domains, all inside",
        "//   the CRU node's 0x5C000 window; hiword write convention, 16 lines/word)",
        "#![allow(clippy::unreadable_literal, reason = \"CG-024-lint-exceptions: generated table keeps the reference's hex offsets for mechanical diffing\")]",
        "",
        "/// One servicable reset line: `(dts id, byte offset, bit)`; each row",
        "/// carries its reference name as a comment.",
        "pub(crate) struct ResetRow {",
        "    /// BSP DT-binding id — the specifier the board dts carries.",
        "    pub dts_id: u32,",
        "    /// Byte offset of the line's control word from the CRU window base.",
        "    pub word_offset: usize,",
        "    /// Line position within the word (0..16; hiword half is the mask).",
        "    pub bit: u8,",
        "}",
        "",
        "pub(crate) const RESET_ROWS: [ResetRow; %d] = [" % len(rows),
    ]
    for dts_id, name, byte, bit in rows:
        out.append(f"    // {name}")
        out.append(
            f"    ResetRow {{ dts_id: {dts_id:#x}, word_offset: {byte:#x}, bit: {bit} }},"
        )
    out.append("];")
    out.append("")

    OUT.write_text("\n".join(out) + "\n")

    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} lines")
    if missing_lut:
        print(f"gaps: {len(missing_lut)} BSP ids without a mainline LUT row:")
        for dts_id, name in missing_lut[:12]:
            print(f"  {dts_id:#x} {name}")
        if len(missing_lut) > 12:
            print(f"  ... and {len(missing_lut) - 12} more")
    if dups:
        print(f"duplicate dts ids (later row wins is NOT applied — table keeps all): {dups}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
