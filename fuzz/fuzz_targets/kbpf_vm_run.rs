#![no_main]

use libfuzzer_sys::fuzz_target;

fn sum_args(r1: u64, r2: u64, r3: u64, r4: u64, r5: u64) -> u64 {
    r1.wrapping_add(r2)
        .wrapping_add(r3)
        .wrapping_add(r4)
        .wrapping_add(r5)
}

const PROGS: &[&[u8]] = &[
    &[
        0xb7, 0x00, 0x00, 0x00, 0x2a, 0x00, 0x00, 0x00, 0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00,
    ],
    &[
        0xb7, 0x00, 0x00, 0x00, 0x28, 0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00,
        0x00, 0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ],
    &[
        0xb7, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xb7, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00,
        0x00, 0x0f, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x07, 0x01, 0x00, 0x00, 0x01, 0x00,
        0x00, 0x00, 0x15, 0x01, 0x01, 0x00, 0x06, 0x00, 0x00, 0x00, 0x05, 0x00, 0xfc, 0xff, 0x00,
        0x00, 0x00, 0x00, 0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ],
    &[
        0x05, 0x00, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00,
    ],
    &[
        0x85, 0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00,
    ],
];

fuzz_target!(|data: &[u8]| {
    let mut vm = kbpf::Vm::new().with_instruction_limit(256);
    let _ = vm.run(data);

    if data.len() >= 40 {
        let regs = kbpf::vm::InitialRegs {
            r1: u64::from_le_bytes(data[0..8].try_into().unwrap()),
            r2: u64::from_le_bytes(data[8..16].try_into().unwrap()),
            r3: u64::from_le_bytes(data[16..24].try_into().unwrap()),
            r4: u64::from_le_bytes(data[24..32].try_into().unwrap()),
            r5: u64::from_le_bytes(data[32..40].try_into().unwrap()),
            ..Default::default()
        };
        let _ = vm.run_with_initial_regs(data, regs);
    }

    for prog in PROGS {
        let _ = vm.run(prog);
    }

    let call_prog: [u8; 16] = [
        0x85, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x95, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ];
    let mut helper_vm = kbpf::Vm::new().with_instruction_limit(256);
    let _ = helper_vm.register_helper(1, sum_args);
    let _ = helper_vm.run_with_initial_regs(
        &call_prog,
        kbpf::vm::InitialRegs {
            r1: 1,
            r2: 2,
            r3: 4,
            r4: 8,
            r5: 16,
            ..Default::default()
        },
    );
});
